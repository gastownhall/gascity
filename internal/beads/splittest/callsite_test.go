import "testing"

func TestFactsFromFramesPicksTheInnermostProductionFrame(t *testing.T) {
	stack := []frameInfo{
		{file: "internal/beads/splittest/projection.go", line: 10, function: "github.com/gastownhall/gascity/internal/beads/splittest.(*view).Get"},
		{file: "<autogenerated>", line: 1, function: "github.com/gastownhall/gascity/internal/beads.SessionStore.Get"},
		{file: "internal/beads/caching_store.go", line: 5, function: "github.com/gastownhall/gascity/internal/beads.(*CachingStore).Get"},
		{file: "internal/api/residency_by_id.go", line: 82, function: "github.com/gastownhall/gascity/internal/api.(*Server).resolveBeadOwner"},
		{file: "internal/api/handler.go", line: 9, function: "github.com/gastownhall/gascity/internal/api.(*Server).handle"},
		{file: "net/http/server.go", line: 2000, function: "net/http.HandlerFunc.ServeHTTP"},
		{file: "internal/api/handler_test.go", line: 40, function: "github.com/gastownhall/gascity/internal/api.TestHandle.func1"},
		{file: "testing/testing.go", line: 1, function: "testing.tRunner"},
	}
	SetPackageUnderTest("internal/api")
	t.Cleanup(func() { SetPackageUnderTest("") })
	facts := factsFromFrames(stack)
	want := Site{File: "internal/api/residency_by_id.go", Line: 82, Func: "api.(*Server).resolveBeadOwner"}
	if facts.site != want {
		t.Fatalf("site = %+v, want %+v", facts.site, want)
	}
	if wantVia := (Site{File: "internal/api/handler.go", Line: 9, Func: "api.(*Server).handle"}); facts.via != wantVia {
		t.Fatalf("via = %+v, want %+v", facts.via, wantVia)
	}
	if facts.pkg != (Site{File: "internal/api/handler.go", Line: 9, Func: "api.(*Server).handle"}) {
		t.Fatalf("pkg = %+v, want the nearest internal/api frame past the site", facts.pkg)
	}
	if facts.test != "TestHandle" {
		t.Fatalf("test = %q, want TestHandle", facts.test)
	}
}

func TestFactsFromFramesSkipsRegisteredPlumbingFiles(t *testing.T) {
	TreatFilesAsPlumbing("cmd/gc/zz_plumbing_fixture.go")
	stack := []frameInfo{
		{file: "cmd/gc/zz_plumbing_fixture.go", line: 3, function: "main.(*policy).Get"},
		{file: "cmd/gc/caller.go", line: 7, function: "main.caller"},
	}
	if got := factsFromFrames(stack).site; got.File != "cmd/gc/caller.go" || got.Func != "main.caller" {
		t.Fatalf("site = %+v, want cmd/gc/caller.go main.caller", got)
	}
}

