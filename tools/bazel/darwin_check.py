#!/usr/bin/env python3
"""Generate //tools/darwincheck, the Linux-hosted darwin compile and lint check.

`go_darwin_check_test` (tools/bazel/rules/go_darwin_check.bzl) builds its deps
for darwin_arm64 without linking, so a _darwin.go file (or one behind
//go:build !linux) is compiled and nogo-linted on Linux instead of reaching the
macOS tier unchecked. This script writes the one target that lists them:
tools/darwincheck/BUILD.bazel, whose deps are every go_library, go_binary and
go_test in the repository, derived from `bazel query` and never hand-written.

Only a target visible to //tools/darwincheck can be a dep. REPO.bazel makes
every target without explicit visibility visible to that package; the few that
set their own restricted visibility are left out of the list, and only when
something listed already builds them:

  - a listed target depends on it (a go_binary's embedded *_lib library, a
    nogo analyzer's test-only internals), so the darwin build of that target
    compiles and checks it too; or
  - it is a cmd/gc test variant (COVERED_BY) and //cmd/gc:gc is listed: the
    variant differs from the plain build only by test files or build tags that
    //cmd/gc:gc_test already covers.

Any other restricted target would silently drop out of the check, so the
script exits 1 naming it. Make its visibility include //tools/darwincheck:
__pkg__, or extend COVERED_BY with the reason it is covered.

Run after gazelle (see `make bazel-sync`); the CI "BUILD files in sync" job
fails when the result differs from what is committed, so a new Go package joins
the check without a hand edit. `--check` reports drift without writing.
`--bazel PATH` names the bazel binary (the offline test passes a fixture).
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys

BUILD = "tools/darwincheck/BUILD.bazel"
TARGET = "//tools/darwincheck:darwin_check_test"
LOAD = 'load("//tools/bazel/rules:go_darwin_check.bzl", "go_darwin_check_test")\n'
KINDS = "^(go_library|go_binary|go_test) rule$"
GO_TARGETS = f'kind("{KINDS}", //...)'

# Restricted-visibility targets covered by another listed target, with the
# reason. The key is not built by the darwin check itself: its darwin build
# would only repeat what the covering target already compiled and linted.
COVERED_BY = {
    "//cmd/gc:gc_drift_new": "//cmd/gc:gc",
    "//cmd/gc:gc_drift_old": "//cmd/gc:gc",
    "//cmd/gc:gc_testhooks": "//cmd/gc:gc",
}

LABEL_KIND_RE = re.compile(r"^(?P<kind>\S+) rule (?P<label>//\S+)$")


class CheckError(Exception):
    """A failure to report on stderr (exit 1) without a traceback."""


def query(bazel: str, expr: str) -> list[str]:
    """Labels bazel's `query --output=label_kind` prints for expr, sorted."""
    cmd = [bazel, "query", "--noshow_progress", "--noshow_loading_progress",
           "--output=label_kind", expr]
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=False)
    if proc.returncode != 0:
        head = expr if len(expr) < 200 else expr[:200] + "..."
        raise CheckError(f"{' '.join(cmd[:2])} failed ({proc.returncode}) for {head}\n{proc.stderr.strip()}")
    labels = []
    for line in proc.stdout.splitlines():
        if not line.strip():
            continue
        m = LABEL_KIND_RE.match(line)
        if not m:
            raise CheckError(f"unexpected line in bazel query output: {line!r}")
        labels.append(m.group("label"))
    return sorted(labels)


def label_set(labels: list[str]) -> str:
    return "set(" + " ".join(labels) + ")"


def split_targets(bazel: str) -> tuple[list[str], list[str]]:
    """(listed, restricted): go targets visible to the check, and those not."""
    everything = query(bazel, GO_TARGETS)
    visible = set(query(bazel, f"visible({TARGET}, {GO_TARGETS})"))
    listed = [label for label in everything if label in visible]
    restricted = [label for label in everything if label not in visible]
    return listed, restricted


def uncovered(bazel: str, listed: list[str], restricted: list[str]) -> list[str]:
    """The restricted targets no listed target builds."""
    if not restricted:
        return []
    reached = set(query(bazel, f"deps({label_set(listed)}) intersect {label_set(restricted)}")) if listed else set()
    listed_set = set(listed)
    return [label for label in restricted
            if label not in reached and COVERED_BY.get(label) not in listed_set]


def render(listed: list[str], restricted: list[str]) -> str:
    out = [LOAD, "\n",
           "# Generated by tools/bazel/darwin_check.py (`make bazel-sync`); do not edit.\n",
           "#\n",
           "# Not visible to this package, so not listed (each is covered through the target\n",
           "# that embeds it or depends on it, or by //cmd/gc:gc):\n"]
    out.extend(f"#   {label}\n" for label in restricted)
    out.append("\ngo_darwin_check_test(\n"
               '    name = "darwin_check_test",\n'
               '    size = "small",\n'
               "    deps = [\n")
    out.extend(f'        "{label}",\n' for label in listed)
    out.append("    ],\n)\n")
    return "".join(out)


def generate(bazel: str, check: bool) -> int:
    try:
        with open(BUILD, encoding="utf-8") as f:
            current = f.read()
    except FileNotFoundError:
        current = None
    if current is None and check:
        print(f"{BUILD} is missing; run `python3 tools/bazel/darwin_check.py` (or `make bazel-sync`)",
              file=sys.stderr)
        return 1

    # bazel's visible() needs the check target to exist, so the very first run
    # writes an empty one, and takes it away again unless it was replaced.
    stub = current is None
    if stub:
        os.makedirs(os.path.dirname(BUILD), exist_ok=True)
        with open(BUILD, "w", encoding="utf-8") as f:
            f.write(render([], []))
    try:
        listed, restricted = split_targets(bazel)
        missing = uncovered(bazel, listed, restricted)
        if missing:
            raise CheckError(
                "restricted-visibility Go targets that nothing listed builds, so the darwin check would skip them:\n"
                + "".join(f"  {label}\n" for label in missing)
                + f"Add //tools/darwincheck:__pkg__ to each one's visibility (or extend COVERED_BY in {sys.argv[0]})")
        out = render(listed, restricted)
        if out == current:
            return 0
        if check:
            print(f"{BUILD} is stale; run `python3 tools/bazel/darwin_check.py` (or `make bazel-sync`)",
                  file=sys.stderr)
            return 1
        tmp = BUILD + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(out)
        os.replace(tmp, BUILD)
        stub = False
        return 0
    finally:
        if stub and os.path.exists(BUILD):
            os.remove(BUILD)
            try:
                os.rmdir(os.path.dirname(BUILD))
            except OSError:
                pass


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    parser.add_argument("--bazel", default=os.environ.get("BAZEL", "bazel"), help="bazel binary")
    args = parser.parse_args(argv)
    os.chdir(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    try:
        return generate(args.bazel, args.check)
    except CheckError as err:
        print(f"darwin_check.py: {err}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
