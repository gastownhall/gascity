package storeclass

import (
	"fmt"
	"path"
	"slices"
	"sort"
	"strconv"
	"strings"
)

// Key is one baseline row's identity: a file (module-relative), the function
// or declaration that encloses the sites ("Func", "Recv.Method", a type or
// package variable name, or "(import)"), and the rule. Counts per enclosing
// function are immune to line drift and still forbid growth
// (scripts/check-residency-boundary.sh has the same reasoning).
type Key struct {
	Path string
	Func string
	Rule Rule
}

// Package is the module-relative package directory k's file lives in, "."
// for the module root.
func (k Key) Package() string { return path.Dir(k.Path) }

func (k Key) String() string { return k.Path + "\t" + k.Func + "\t" + string(k.Rule) }

// BaselineHeader opens every generated baseline.
const BaselineHeader = `# storeclass baseline: the raw-store debt outside the allowlist, as
# path<TAB>enclosing function<TAB>rule<TAB>count.
#
# Generated by tools/nogo/analyzers/storeclass/cmd/storeclass-baseline. It may
# only SHRINK: nogo fails above a pinned count (new debt) and on a pinned count
# the tree no longer reaches (regenerate in the commit that retires a site),
# and TestBaselineOnlyShrinks fails if any package's count for a rule grows past
# ceiling.txt. Never raise a count by hand.
`

// AllowedHeader opens allowed.txt.
const AllowedHeader = `# storeclass allowed: the findings an allowlist entry for one file exempts
# from nogo (cmd/gc's storage_boot.go and infra_class_*.go), as
# path<TAB>enclosing function<TAB>rule<TAB>count.
#
# Generated by tools/nogo/analyzers/storeclass/cmd/storeclass-baseline with
# baseline.txt. The storeclass baseline workflow fails when it does not match
# the tree, and its growth gate judges it like baseline.txt: a new or raised
# row needs the storeclass/baseline-raise label, so moving debt into an
# allowlisted file is a raise. Never raise a count by hand.
`

// ParseBaseline reads a baseline, or allowed.txt, which has its shape:
// tab-separated rows of path, function, rule and a positive count; blank
// lines and # comments are skipped.
func ParseBaseline(text string) (map[Key]int, error) {
	rows := map[Key]int{}
	for i, line := range strings.Split(text, "\n") {
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 4 {
			return nil, fmt.Errorf("baseline line %d: want path<TAB>func<TAB>rule<TAB>count, got %q", i+1, line)
		}
		k := Key{Path: f[0], Func: f[1], Rule: Rule(f[2])}
		if !slices.Contains(Rules, k.Rule) {
			return nil, fmt.Errorf("baseline line %d: unknown rule %q", i+1, f[2])
		}
		n, err := strconv.Atoi(f[3])
		if err != nil || n <= 0 {
			return nil, fmt.Errorf("baseline line %d: count %q is not a positive integer", i+1, f[3])
		}
		if _, dup := rows[k]; dup {
			return nil, fmt.Errorf("baseline line %d: duplicate row %s", i+1, k)
		}
		rows[k] = n
	}
	return rows, nil
}

// FormatBaseline writes rows canonically: the header, then rows sorted by
// path, function and rule.
func FormatBaseline(rows map[Key]int) string { return formatRows(BaselineHeader, rows) }

// FormatAllowed writes allowed.txt canonically, as FormatBaseline writes a
// baseline.
func FormatAllowed(rows map[Key]int) string { return formatRows(AllowedHeader, rows) }

func formatRows(header string, rows map[Key]int) string {
	keys := make([]Key, 0, len(rows))
	for k := range rows {
		keys = append(keys, k)
	}
	sortKeys(keys)
	var b strings.Builder
	b.WriteString(header)
	for _, k := range keys {
		fmt.Fprintf(&b, "%s\t%d\n", k, rows[k])
	}
	return b.String()
}

func sortKeys(keys []Key) {
	sort.Slice(keys, func(i, j int) bool {
		a, b := keys[i], keys[j]
		if a.Path != b.Path {
			return a.Path < b.Path
		}
		if a.Func != b.Func {
			return a.Func < b.Func
		}
		return a.Rule < b.Rule
	})
}

// CeilingKey is one ceiling row: a package and a rule.
type CeilingKey struct {
	Package string
	Rule    Rule
}

// Totals sums rows per package and rule: what ceiling.txt pins.
func Totals(rows map[Key]int) map[CeilingKey]int {
	out := map[CeilingKey]int{}
	for k, n := range rows {
		out[CeilingKey{Package: k.Package(), Rule: k.Rule}] += n
	}
	return out
}

// CeilingHeader opens ceiling.txt.
const CeilingHeader = `# storeclass ceiling: baseline.txt's total per package and rule, as
# package<TAB>rule<TAB>count. TestBaselineOnlyShrinks holds the baseline to
# exactly these totals, so a shrink lowers a row here in the same commit and a
# growth fails. The generator only ever lowers a row; raising one is a
# coordinator decision, made by hand, and visible in review.
`

// ParseCeiling reads ceiling.txt.
func ParseCeiling(text string) (map[CeilingKey]int, error) {
	rows := map[CeilingKey]int{}
	for i, line := range strings.Split(text, "\n") {
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 3 {
			return nil, fmt.Errorf("ceiling line %d: want package<TAB>rule<TAB>count, got %q", i+1, line)
		}
		k := CeilingKey{Package: f[0], Rule: Rule(f[1])}
		if !slices.Contains(Rules, k.Rule) {
			return nil, fmt.Errorf("ceiling line %d: unknown rule %q", i+1, f[1])
		}
		n, err := strconv.Atoi(f[2])
		if err != nil || n <= 0 {
			return nil, fmt.Errorf("ceiling line %d: count %q is not a positive integer", i+1, f[2])
		}
		if _, dup := rows[k]; dup {
			return nil, fmt.Errorf("ceiling line %d: duplicate row %s %s", i+1, k.Package, k.Rule)
		}
		rows[k] = n
	}
	return rows, nil
}

// FormatCeiling writes ceiling rows canonically.
func FormatCeiling(rows map[CeilingKey]int) string {
	keys := make([]CeilingKey, 0, len(rows))
	for k := range rows {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		if keys[i].Package != keys[j].Package {
			return keys[i].Package < keys[j].Package
		}
		return keys[i].Rule < keys[j].Rule
	})
	var b strings.Builder
	b.WriteString(CeilingHeader)
	for _, k := range keys {
		fmt.Fprintf(&b, "%s\t%s\t%d\n", k.Package, k.Rule, rows[k])
	}
	return b.String()
}
