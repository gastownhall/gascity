// Command gen-seat-digest writes contrib/seat-digest/AGENTS.seat.md, the
// part of the root AGENTS.md that a gc-managed agent seat loads instead of
// the whole file. The digest is the text between
// "<!-- seat:begin -->" and "<!-- seat:end -->" lines of AGENTS.md, in file
// order, with the headings each region sits under. Generation fails when the
// digest would drop a rule: every AGENTS.md paragraph, list item or table
// row that says must, never, do not, don't, hard rule or hard ban has to sit
// inside a marked region.
//
// Run it from the repository root after editing AGENTS.md:
//
//	bazel run //cmd/gen-seat-digest
//
// and check freshness with -check (TestCommittedSeatDigestIsFreshAndKeepsEveryRule
// runs the same check under bazel test).
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
)

const (
	agentsPath = "AGENTS.md"
	digestPath = "contrib/seat-digest/AGENTS.seat.md"

	markerBegin = "<!-- seat:begin -->"
	markerEnd   = "<!-- seat:end -->"

	// digestBudgetBytes caps the digest so marking stays selective: the
	// digest exists to be much smaller than AGENTS.md.
	digestBudgetBytes = 12000
)

const digestHeader = "# Gas City: agent seat digest of AGENTS.md\n\n" +
	"Generated by `cmd/gen-seat-digest` from the marked regions of the root\n" +
	"`AGENTS.md`; do not edit. A gc-managed seat loads this digest instead of\n" +
	"the whole file. Read the root `AGENTS.md` itself before you change code,\n" +
	"tests or docs in this repository.\n\n"

// ruleRE matches the words that make a block a rule the digest must keep.
var ruleRE = regexp.MustCompile(`(?i)\b(must|never|do not|don't|hard[- ]rule|hard ban)\b`)

var (
	headingRE  = regexp.MustCompile(`^(#{1,6}) `)
	listItemRE = regexp.MustCompile(`^(?:[-*+]|\d+\.) `)
)

type generatorOptions struct {
	Root  string
	Check bool
}

func main() {
	check := flag.Bool("check", false, "fail if the committed digest is stale or drops a rule")
	root := flag.String("root", "", "repository root (defaults to the bazel run workspace, else the source root)")
	flag.Parse()
	resolvedRoot := *root
	if resolvedRoot == "" {
		resolvedRoot = os.Getenv("BUILD_WORKSPACE_DIRECTORY")
	}
	if resolvedRoot == "" {
		_, source, _, ok := runtime.Caller(0)
		if !ok {
			fmt.Fprintln(os.Stderr, "gen-seat-digest: cannot locate the repository root; pass -root")
			os.Exit(1)
		}
		resolvedRoot = filepath.Clean(filepath.Join(filepath.Dir(source), "../.."))
	}
	if err := runGenerator(generatorOptions{Root: resolvedRoot, Check: *check}); err != nil {
		fmt.Fprintln(os.Stderr, "gen-seat-digest:", err)
		os.Exit(1)
	}
}

func runGenerator(options generatorOptions) error {
	src, err := os.ReadFile(filepath.Join(options.Root, agentsPath))
	if err != nil {
		return fmt.Errorf("reading %s: %w", agentsPath, err)
	}
	digest, err := generate(string(src))
	if err != nil {
		return fmt.Errorf("%s: %w", agentsPath, err)
	}
	if missing := missingRuleBlocks(string(src), digest); len(missing) > 0 {
		return fmt.Errorf("%s: the seat digest would drop %d rule block(s); wrap each in %s ... %s:\n%s",
			agentsPath, len(missing), markerBegin, markerEnd, strings.Join(missing, "\n---\n"))
	}
	out := filepath.Join(options.Root, digestPath)
	if options.Check {
		committed, err := os.ReadFile(out)
		if err != nil {
			return fmt.Errorf("reading %s: %w (run `bazel run //cmd/gen-seat-digest`)", digestPath, err)
		}
		if !bytes.Equal(committed, []byte(digest)) {
			return fmt.Errorf("%s is stale: run `bazel run //cmd/gen-seat-digest` and commit the result", digestPath)
		}
		return nil
	}
	return writeFileAtomic(out, []byte(digest))
}

// generate returns the seat digest of an AGENTS.md source.
func generate(src string) (string, error) {
	type heading struct {
		level   int
		text    string
		emitted bool
	}
	var (
		stack    []heading
		chunks   []string
		region   []string
		inRegion bool
		inFence  bool
		regions  int
	)
	// emitAncestors adds the not yet emitted headings a region sits under.
	// The level-1 document title is never one: the digest has its own.
	emitAncestors := func() {
		for j := range stack {
			if stack[j].level > 1 && !stack[j].emitted {
				chunks = append(chunks, stack[j].text)
				stack[j].emitted = true
			}
		}
	}
	flush := func() error {
		lines := trimBlankLines(region)
		region = nil
		if len(lines) == 0 {
			return errors.New("empty seat region")
		}
		chunks = append(chunks, strings.Join(lines, "\n"))
		return nil
	}
	for i, line := range strings.Split(src, "\n") {
		trimmed := strings.TrimSpace(line)
		if !inFence && (strings.Contains(line, markerBegin) || strings.Contains(line, markerEnd)) {
			if trimmed != markerBegin && trimmed != markerEnd {
				return "", fmt.Errorf("line %d: a seat marker must be alone on its line", i+1)
			}
			if trimmed == markerBegin {
				if inRegion {
					return "", fmt.Errorf("line %d: %s inside an open region", i+1, markerBegin)
				}
				inRegion = true
				regions++
				continue
			}
			if !inRegion {
				return "", fmt.Errorf("line %d: %s without %s", i+1, markerEnd, markerBegin)
			}
			inRegion = false
			if err := flush(); err != nil {
				return "", fmt.Errorf("line %d: %w", i+1, err)
			}
			continue
		}
		isHeading := false
		if strings.HasPrefix(trimmed, "```") {
			inFence = !inFence
		} else if m := headingRE.FindStringSubmatch(line); m != nil && !inFence {
			isHeading = true
			level := len(m[1])
			for len(stack) > 0 && stack[len(stack)-1].level >= level {
				stack = stack[:len(stack)-1]
			}
			if inRegion && len(trimBlankLines(region)) == 0 {
				emitAncestors()
			}
			stack = append(stack, heading{level: level, text: line, emitted: inRegion})
		}
		if !inRegion {
			continue
		}
		if !isHeading && trimmed != "" && len(trimBlankLines(region)) == 0 {
			emitAncestors()
		}
		region = append(region, line)
	}
	if inRegion {
		return "", fmt.Errorf("%s without %s", markerBegin, markerEnd)
	}
	if regions == 0 {
		return "", fmt.Errorf("no %s regions", markerBegin)
	}
	return digestHeader + strings.Join(chunks, "\n\n") + "\n", nil
}

// ruleBlocks returns every paragraph, list item and table row of src that
// states a rule, with marker lines removed.
func ruleBlocks(src string) []string {
	var out []string
	for _, b := range blocks(src) {
		if ruleRE.MatchString(b) {
			out = append(out, b)
		}
	}
	return out
}

// missingRuleBlocks returns the rule blocks of src that digest does not
// contain verbatim.
func missingRuleBlocks(src, digest string) []string {
	var missing []string
	for _, b := range ruleBlocks(src) {
		if !strings.Contains(digest, b) {
			missing = append(missing, b)
		}
	}
	return missing
}

// blocks splits markdown into paragraphs, list items (with their indented
// continuation), table rows and fenced code blocks. Headings and seat
// marker lines are not blocks.
func blocks(src string) []string {
	var lines []string
	for _, line := range strings.Split(src, "\n") {
		if t := strings.TrimSpace(line); t == markerBegin || t == markerEnd {
			continue
		}
		lines = append(lines, line)
	}
	var out []string
	var cur []string
	kind := ""
	emit := func() {
		if trimmed := trimBlankLines(cur); len(trimmed) > 0 {
			out = append(out, strings.Join(trimmed, "\n"))
		}
		cur, kind = nil, ""
	}
	nextIndented := func(i int) bool {
		for j := i + 1; j < len(lines); j++ {
			if strings.TrimSpace(lines[j]) == "" {
				continue
			}
			return strings.HasPrefix(lines[j], " ")
		}
		return false
	}
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if kind == "fence" {
			cur = append(cur, line)
			if strings.HasPrefix(trimmed, "```") {
				emit()
			}
			continue
		}
		if kind == "item" && (strings.HasPrefix(line, " ") || (trimmed == "" && nextIndented(i))) {
			cur = append(cur, line)
			continue
		}
		switch {
		case trimmed == "":
			emit()
		case strings.HasPrefix(trimmed, "```"):
			emit()
			kind = "fence"
			cur = append(cur, line)
		case headingRE.MatchString(line):
			emit()
		case strings.HasPrefix(trimmed, "|"):
			emit()
			out = append(out, line)
		case listItemRE.MatchString(line):
			emit()
			kind = "item"
			cur = append(cur, line)
		default:
			if kind == "item" {
				emit()
			}
			kind = "para"
			cur = append(cur, line)
		}
	}
	emit()
	return out
}

func trimBlankLines(lines []string) []string {
	for len(lines) > 0 && strings.TrimSpace(lines[0]) == "" {
		lines = lines[1:]
	}
	for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
		lines = lines[:len(lines)-1]
	}
	return lines
}

func writeFileAtomic(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("creating %s: %w", filepath.Dir(path), err)
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".seat-digest-*")
	if err != nil {
		return fmt.Errorf("creating temp file for %s: %w", path, err)
	}
	defer os.Remove(tmp.Name()) //nolint:errcheck // best-effort cleanup; a renamed file is gone already
	if _, err := tmp.Write(data); err != nil {
		tmp.Close() //nolint:errcheck,gosec // the write error is the one reported
		return fmt.Errorf("writing %s: %w", tmp.Name(), err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("closing %s: %w", tmp.Name(), err)
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return fmt.Errorf("chmod %s: %w", tmp.Name(), err)
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return fmt.Errorf("renaming %s to %s: %w", tmp.Name(), path, err)
	}
	return nil
}
