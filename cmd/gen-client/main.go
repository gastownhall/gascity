// Command gen-client generates the typed Go API client from the live
// OpenAPI spec.
//
// Pipeline:
//  1. Fetch the 3.0-downgrade spec directly from a SupervisorMux built
//     against an empty resolver. Huma v2 emits the downgrade
//     automatically; oapi-codegen v2.6.0 consumes it cleanly where it
//     chokes on 3.1. The supervisor owns every operation, so one fetch
//     yields the entire API surface — no merge step.
//  2. Pipe the spec unchanged to oapi-codegen. There is NO preprocessing.
//     The routes we register ARE the routes we expose. Every schema and
//     path in the generated client matches what the server publishes to
//     external consumers — no hidden rename, no hidden path rewrite.
//     skip-prune keeps documentation-only compatibility components
//     available to in-tree callers that still deserialize those shapes.
//  3. Replace oapi-codegen's "Code generated by <module> version <v>"
//     line with a fixed header. That line reports how the oapi-codegen
//     binary was built (go install embeds module info; a Bazel build of
//     the same pinned version does not), not anything about the output,
//     so normalizing it keeps the committed client byte-identical across
//     both build paths.
//  4. Write the generated client to stdout.
//
// Usage:
//
//	go run ./cmd/gen-client [-oapi-codegen PATH] > internal/api/genclient/client_gen.go
//
// -oapi-codegen defaults to the oapi-codegen on PATH. The version is pinned
// in MODULE.bazel (and installed by `make install-oapi-codegen`).
//
// Or via go:generate in internal/api/genclient/doc.go. A CI drift test
// regenerates the client and diffs against the committed file so the
// spec is the source of truth.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"net/http"
	"net/http/httptest"
	"os"
	"os/exec"
	"regexp"
	"time"

	"github.com/gastownhall/gascity/internal/api"
)

// generatedHeader replaces oapi-codegen's build-identity header line.
const generatedHeader = "// Code generated by github.com/oapi-codegen/oapi-codegen/v2 via cmd/gen-client. DO NOT EDIT."

var oapiCodegenHeader = regexp.MustCompile(`(?m)^// Code generated by .* DO NOT EDIT\.$`)

func main() {
	oapiCodegen := flag.String("oapi-codegen", "oapi-codegen", "oapi-codegen binary to run (name on PATH or path)")
	flag.Parse()
	if err := run(*oapiCodegen); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(oapiCodegen string) error {
	// Step 1: fetch the 3.0-downgraded spec from the supervisor.
	sm := api.NewSupervisorMux(emptyResolver{}, nil, false, "", "", time.Time{})
	req := httptest.NewRequest(http.MethodGet, "/openapi-3.0.json", nil)
	rec := httptest.NewRecorder()
	sm.ServeHTTP(rec, req)
	if rec.Code != http.StatusOK {
		return fmt.Errorf("GET /openapi-3.0.json returned %d: %s", rec.Code, rec.Body.String())
	}

	// Step 2: write the spec verbatim to a temp file for oapi-codegen.
	tmp, err := os.CreateTemp("", "gc-openapi-3.0-*.json")
	if err != nil {
		return fmt.Errorf("tempfile: %w", err)
	}
	defer func() { _ = os.Remove(tmp.Name()) }()
	if _, err := tmp.Write(rec.Body.Bytes()); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("write temp spec: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close temp spec: %w", err)
	}

	// Step 3: invoke oapi-codegen. Output goes to stdout — the caller
	// redirects it to internal/api/genclient/client_gen.go.
	var generated bytes.Buffer
	cmd := exec.Command(oapiCodegen, "-generate", "types,client,skip-prune", "-package", "genclient", tmp.Name())
	cmd.Stdout = &generated
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("oapi-codegen: %w", err)
	}
	out, err := canonicalizeGeneratedHeader(generated.Bytes())
	if err != nil {
		return err
	}
	if _, err := os.Stdout.Write(out); err != nil {
		return fmt.Errorf("write client: %w", err)
	}
	return nil
}

// canonicalizeGeneratedHeader replaces the single oapi-codegen
// "Code generated by ... DO NOT EDIT." line with generatedHeader.
func canonicalizeGeneratedHeader(src []byte) ([]byte, error) {
	if n := len(oapiCodegenHeader.FindAllIndex(src, -1)); n != 1 {
		return nil, fmt.Errorf("oapi-codegen output has %d generated-code header lines, want exactly 1", n)
	}
	return oapiCodegenHeader.ReplaceAllLiteral(src, []byte(generatedHeader)), nil
}

// emptyResolver implements api.CityResolver with no cities. Schema
// generation is reflection-based and never calls resolver methods.
type emptyResolver struct{}

func (emptyResolver) ListCities() []api.CityInfo   { return nil }
func (emptyResolver) CityState(_ string) api.State { return nil }
